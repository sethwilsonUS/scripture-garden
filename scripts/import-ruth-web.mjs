import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseRuthUsfm } from "../lib/scripture/usfm.ts";
import {
  WEB_SOURCE_FILE,
  WEB_SOURCE_URL,
  WEB_TRANSLATION,
} from "../lib/scripture/constants.ts";
import {
  assertRuthCorpusShape,
  assertWebMetadataShape,
} from "../lib/scripture/corpus.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const usfm = execFileSync(
  "sh",
  ["-c", `curl -sL ${WEB_SOURCE_URL} | bsdtar -xOf - ${WEB_SOURCE_FILE}`],
  { encoding: "utf8", maxBuffer: 4 * 1024 * 1024 },
);

const verses = parseRuthUsfm(usfm);
assertWebMetadataShape();
assertRuthCorpusShape(verses);

const importedAt = new Date().toISOString();
const seed = {
  translation: WEB_TRANSLATION,
  importedAt,
  verses,
};

const jsonPath = join(root, "data", "ruth-web.json");
mkdirSync(dirname(jsonPath), { recursive: true });
writeFileSync(`${jsonPath}\n`.trim(), `${JSON.stringify(seed, null, 2)}\n`);

const tsPath = join(root, "convex", "seedData", "ruthWeb.ts");
mkdirSync(dirname(tsPath), { recursive: true });
writeFileSync(
  tsPath,
  `// Generated by scripts/import-ruth-web.mjs from ${WEB_SOURCE_URL}\n` +
    `export const ruthWebSeed = ${JSON.stringify(seed, null, 2)} as const;\n`,
);

console.log(`Imported ${verses.length} Ruth verses from ${WEB_SOURCE_FILE}.`);
